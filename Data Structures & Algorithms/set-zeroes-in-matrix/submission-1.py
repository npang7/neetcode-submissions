class Solution:
    def setZeroes(self, matrix: List[List[int]]) -> None:
        rows = len(matrix)
        cols = len(matrix[0])

        first_row_zero = False
        first_col_zero = False

        # 1. 记录第一行、第一列原本是否有 0
        for j in range(cols):
            if matrix[0][j] == 0:
                first_row_zero = True

        for i in range(rows):
            if matrix[i][0] == 0:
                first_col_zero = True

        # 2. 检查内部区域，用第一列、第一行标记需要清零的行和列
        for i in range(1, rows):
            for j in range(1, cols):
                if matrix[i][j] == 0:
                    matrix[i][0] = 0
                    matrix[0][j] = 0

        # 3. 根据标记，清零内部区域
        for i in range(1, rows):
            for j in range(1, cols):
                if matrix[i][0] == 0 or matrix[0][j] == 0:
                    matrix[i][j] = 0

        # 4. 最后处理第一行、第一列，避免提前破坏标记
        if first_row_zero:
            for j in range(cols):
                matrix[0][j] = 0

        if first_col_zero:
            for i in range(rows):
                matrix[i][0] = 0


# Set Matrix Zeroes（矩阵置零）：O(1) 额外空间版本
#
# 一、分类 / 关键词
# - Array / List（数组 / 列表）：二维列表存储矩阵。
# - Matrix（矩阵）：根据行列关系处理元素。
# - In-place Marking（原地标记）：借用第一行、第一列保存标记。
#
# 二、记忆思路
#
# 1. 先保存第一行、第一列的原始情况。
#    - first_row_zero：第一行原本是否有 0。
#    - first_col_zero：第一列原本是否有 0。
#    - 必须提前记录，因为后面会修改它们来存放标记。
#
# 2. 扫描内部区域，两个下标都从 1 开始。
#    - 如果 matrix[i][j] == 0：
#      matrix[i][0] = 0：标记第 i 行需要清零。
#      matrix[0][j] = 0：标记第 j 列需要清零。
#    - 第一列保存行标记，第一行保存列标记。
#
# 3. 再次扫描内部区域，根据标记清零。
#    - 如果 matrix[i][0] == 0 或 matrix[0][j] == 0：
#      当前位置需要清零。
#    - 只修改内部，不破坏边界上的标记。
#
# 4. 最后根据两个布尔变量，处理第一行、第一列。
#    - first_row_zero 为 True：清零第一行。
#    - first_col_zero 为 True：清零第一列。
#
# 快速记忆：
# 先存边界原情况，再借边界做标记；
# 根据标记清内部，最后处理边界本身。
#
# 三、易错点
#
# - 只根据原本的 0 决定清零范围，新产生的 0 不能继续传播。
# - 不能发现 0 就立即清零整行整列，否则会污染后续判断。
# - 内部扫描从下标 1 开始，避免把新写入的边界标记当作原始数据。
# - 行或列任意一个有标记就清零，用 or，不是 and。
# - 第一行、第一列必须最后清零，否则会提前破坏标记。
# - 第一行出现标记 0，不代表第一行原本需要全部清零。
# - 两个布尔变量分别保存第一行、第一列的情况，不能混淆。
# - matrix[0][0] 是第一行、第一列的交点：
#   如果它原本为 0，两个布尔变量都会变成 True。
# - 只有一行或一列时，内部循环可能不执行，最后的边界处理仍然有效。
#
# 四、相关 Python 基础
#
# - len(matrix)：行数；len(matrix[0])：列数。
# - matrix[i][j]：第 i 行、第 j 列。
# - matrix[0][j]：第一行的第 j 个位置。
# - matrix[i][0]：第 i 行的第一个位置。
# - range(1, rows)：跳过第一行，最后检查到 rows - 1。
# - False / True：布尔值，用于记录某个条件是否成立。
# - if first_row_zero：等价于判断该变量是否为 True。
# - 原地修改输入，不代表额外空间一定为 O(1)：
#   集合版本也修改原矩阵，但集合仍占 O(m + n) 空间。
#
# 五、复杂度
#
# - 时间：O(m × n)，常数次扫描矩阵。
# - 额外空间：O(1)，只使用固定数量的变量。
# - 第一行、第一列属于输入矩阵，不算额外分配的空间。
#
#
# ============================================================
# 做题时，如何选择数据结构？
# ============================================================
#
# 一、先问“需要什么操作”，再选数据结构
#
# 1. 我需要保存什么信息？
#    - 是否出现过？出现次数？对应位置？处理顺序？最小值？
#
# 2. 最频繁的操作是什么？
#    - 查询、插入、删除、取最小值、按顺序取出，还是访问两端？
#
# 3. 原数据有什么性质？
#    - 已排序？值域很小？是连续区间？是树或图？允许修改吗？
#
# 4. 数据规模和空间要求是什么？
#    - 方案能否满足复杂度要求？
#    - 先写清楚可行方案，再考虑优化。
#
#
# 二、常见需求与对应选择
#
# 1. 只需要判断“某个元素是否出现过” → set
#    - 自动去重，平均 O(1) 查询、插入。
#    - 例如：访问过的状态、重复元素、需要清零的行号。
#
# 2. 需要“键 → 对应信息” → dict / Hash Map
#    - 对应信息可以是次数、下标、节点、列表等。
#    - 平均 O(1) 查询、插入。
#    - 例如：数字 → 下标，字符 → 次数，旧节点 → 新节点。
#
# 3. 键是小范围、连续整数 → 考虑 list 作为计数表或状态表
#    - 可以用下标直接访问。
#    - 例如：26 个小写字母的出现次数。
#    - 如果键稀疏、范围很大或不是整数，dict 往往更合适。
#
# 4. 需要“后放入的先处理” → Stack
#    - Python 常用 list 的 append() 和 pop()。
#    - 例如：括号匹配、撤销、表达式计算。
#
# 5. 需要“先放入的先处理” → Queue
#    - Python 常用 collections.deque。
#    - append() 入队，popleft() 出队。
#    - 例如：BFS、按层处理。
#
# 6. 需要反复取出当前最小值或最大值 → Heap
#    - Python heapq 默认是最小堆。
#    - 查看堆顶 O(1)，插入、弹出 O(log n)。
#    - 例如：Top K、会议室最早结束时间、多路归并。
#    - 如果只求一次最大值，通常直接扫描，不必用堆。
#
# 7. 需要高效操作两端 → deque
#    - 例如：单调队列维护滑动窗口最大值。
#
# 8. 需要按节点关系修改前后连接 → Linked List
#    - 已知节点时，双向链表可以 O(1) 删除或移动。
#    - 查找节点本身通常不是 O(1)。
#    - LRU Cache 用 dict 找节点，再用双向链表调整顺序。
#
# 9. 需要按前缀逐字符搜索 → Trie
#    - 例如：前缀查询、字典单词搜索。
#
# 10. 需要表示节点之间的连接 → Graph / Adjacency List
#     - 邻接表保存每个节点的邻居。
#     - 再根据任务选择 DFS、BFS、拓扑排序等算法。
#
# 11. 需要反复合并集合、判断是否连通 → Union Find
#     - 例如：连通分量、无向图中的冗余连接。
#
#
# 三、数据结构和算法技巧要区分
#
# - 数据结构：list、dict、set、stack、queue、heap、tree 等。
# - 算法 / 技巧：排序、二分、滑动窗口、贪心、DP、回溯等。
# - 两者经常组合使用：
#   滑动窗口 + dict：维护窗口内的字符计数。
#   BFS + deque + set：按层搜索，并避免重复访问。
#   排序 + heap：按开始时间安排会议，维护最早结束时间。
#   DP + list：用数组保存已经计算过的状态。
#
#
# 四、进一步优化：真的需要保存所有信息吗？
#
# 1. 能否只保留一个累计状态？
#    - Jump Game：只需维护最远可达位置。
#
# 2. 能否只保留上一层状态？
#    - 部分 DP 可以压缩空间，但要检查转移依赖与遍历方向。
#
# 3. 能否借用输入保存标记？
#    - Set Matrix Zeroes：第一行、第一列代替两个集合。
#    - 前提是允许修改，而且不能丢失之后仍需要的原始信息。
#
# 4. 能否先排序，让后续处理更简单？
#    - 区间排序后，可以线性扫描比较和合并。
#    - 但要考虑排序成本，以及是否允许改变输入顺序。
#
# 快速记忆：
# 只问有没有，用 set；
# 需要对应信息，用 dict；
# 后进先出用栈，先进先出用队列；
# 反复取最值用堆；
# 再看能否只存少量状态，或借用输入做标记。