class Solution:
    def rob(self, nums: List[int]) -> int:
        n = len(nums)

        # dp[i]：考虑前 i 间房子，最多能偷到的钱
        dp = [0] * (n + 1)
        # 没有房子时，金额为 0
        dp[0] = 0
        # 只有第一间房子时，最大金额就是它的钱
        dp[1] = nums[0]

        # 从考虑前 2 间开始，一直计算到全部 n 间
        for i in range(2, n + 1):
            # 不偷当前这间：使用前 i - 1 间的最大金额
            skip = dp[i - 1]
            # 偷当前这间：前 i - 2 间的最大金额，加上当前的钱
            take = dp[i - 2] + nums[i - 1]
            # 选择金额较大的方案
            dp[i] = max(skip, take)

        return dp[n]



# 每考虑一间房子，就问自己：这间房子偷，还是不偷？
# 假设我们正在考虑最后一间房子：
# - 不偷它：直接使用前面那些房子能得到的最大金额。
# - 偷它：它前面紧挨着的那间就不能偷，再加上更前面那些房子能得到的最大金额。
# 比较这两种选择，取较大的一个。这就可以用动态规划来计算。
# 注意：dp[i] 不要求一定偷第 i 间房子。 它保存的是考虑前 i 间房子时，所有合法选择中的最大金额。


# 第一种：不偷这间房子。
# 只考虑前 i - 1 间房子即可，最大金额是：dp[i - 1]
# 第二种：偷这间房子。
# 那么紧挨着它的前一间不能偷，只能从前 i - 2 间房子里选择。
# 最大金额是：dp[i - 2] + nums[i - 1]

#！！前 i 间房子的最后一间，在数组里的下标是 i - 1。
# 所以代码里的两个写法分别表示：
# dp[3]    # 考虑前 3 间房子，最多能偷到多少钱nums[2]  # 第 3 间房子里面有多少钱
# 记住：第 1 间用 nums[0]，第 2 间用 nums[1]，第 i 间就用 nums[i - 1]。

